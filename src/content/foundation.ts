import type { Exercise, Lesson } from '../domain/types.ts'

type Choice = [
  text: string,
  question: string,
  options: [string, string, string],
  correct: number,
  hint: string,
  explanation: string,
]
type Recall = [question: string, answer: string, hint: string, explanation: string]
type Unit = {
  id: string
  title: string
  goal: string
  topic: Lesson['topic']
  phrase: string
  translation: string
  note: string
  read: Choice
  recall: Recall
  listen: Choice
  review: Recall
  speaking: string
  writing: string
  check: string[]
  checkpoint?: number
}
function choice(id: string, data: Choice, listening = false): Exercise {
  const [text, prompt, options, correct, hint, explanation] = data
  return {
    id,
    kind: 'choice',
    prompt,
    options,
    answers: [options[correct]],
    hint,
    explanation,
    ...(listening ? { audioText: text } : { passage: text }),
  }
}
function recall(id: string, [prompt, answer, hint, explanation]: Recall): Exercise {
  return { id, kind: 'input', prompt, answers: [answer], hint, explanation }
}
