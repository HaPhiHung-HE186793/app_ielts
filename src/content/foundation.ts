const themes = {
  'Đời sống': ['sand', 'sun'],
  'Giải trí': ['mint', 'game'],
  'Ăn uống': ['peach', 'coffee'],
  'Học tập': ['lavender', 'study'],
} as const
function lesson(unit: Unit, day: number): Lesson {
  return {
    id: unit.id,
    day,
    title: unit.title,
    subtitle: unit.goal,
    topic: unit.topic,
    color: themes[unit.topic][0],
    icon: themes[unit.topic][1],
    minutes: 5,
    phrase: unit.phrase,
    translation: unit.translation,
    note: unit.note,
    goal: unit.goal,
    exercises: [
      choice('reading', unit.read),
      recall('recall', unit.recall),
      choice('listening', unit.listen, true),
    ],
    review: recall(`${unit.id}-review`, unit.review),
    reflection: unit.writing,
    speaking: unit.speaking,
    selfCheck: unit.check,
    ...(unit.checkpoint ? { checkpoint: unit.checkpoint } : {}),
  }
}
export const additionalLessons = units.map((unit, index) => lesson(unit, index + 8))
export const weeklyChecks = checkpoints.map((unit, index) => lesson(unit, (index + 1) * 7))
